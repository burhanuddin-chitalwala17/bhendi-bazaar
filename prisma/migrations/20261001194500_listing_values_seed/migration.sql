-- The permitted answers to the listing facts, read off the platforms' own bulk-upload templates
-- (listing-vocabulary/categories D3; docs/INTEGRATIONS.md).
--
-- Reference data, so a data migration rather than the seed: `prisma/seed.ts` is permanently
-- dev-only and deletes every table, while `vercel.json` runs `prisma migrate deploy` before every
-- build — so a migration reaches every environment on merge and the seed reaches none
-- (CLAUDE.md Invariant 7, docs/OPERATIONS.md). The test is whether production breaks without it,
-- and without these a product form has empty dropdowns.
--
-- The union of what Flipkart and Meesho permit, not the intersection: the shops do not disagree
-- about what to call a colour — 31 of the 35 Flipkart publishes appear on Meesho spelled
-- identically — they disagree about how many colours exist. Taking the narrower list would mean a
-- colour the shop genuinely sells could not be recorded at all, and the mapping work is the same
-- either way. Values both platforms name sort first, so the common ones are at the top of a list.
--
-- `orgId` is NULL: these are platform-provided and visible to every shop. A shop's own additions
-- carry its id and are refused as duplicates only within that shop.
--
-- Idempotent on the partial unique index over (list, key) WHERE orgId IS NULL, so re-running or
-- replaying this migration is a no-op rather than a duplicate-key failure.

