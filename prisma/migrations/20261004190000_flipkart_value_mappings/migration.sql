-- Flipkart's word for each of our answers (channel-registry D3, spec R5; ADR-0045).
--
-- Matched, not guessed. Our vocabulary is the **union** of what Flipkart and Meesho permit
-- (20261001194500_listing_values_seed), so a value Meesho has and Flipkart does not is expected
-- rather than a fault. 468 of the 834 values in lists Flipkart has a vocabulary for match it
-- exactly; the rest carry no row and surface in the register's worklist, where the platform owner
-- maps each once for every product that uses it. Nothing here invents a word: a tool that guessed
-- would be wrong at the rate its guesses looked plausible, and an unmapped answer is reported
-- rather than approximated (spec R5).
--
-- The bulk of what is absent is colour — our list carries 186, Flipkart permits 35. A seller who
-- answers "Baby Pink" is told Flipkart has no word for it, which is true and fixable, rather than
-- quietly listed as Pink.
--
-- **One thing this does not yet record.** Flipkart's permitted values differ per node — sixteen
-- colours appear in all eleven nodes that have one, nineteen more in only some
-- (docs/INTEGRATIONS.md). These rows are the translation, which is the same wherever the word
-- appears; whether a given node permits it is a separate question and no row here claims to
-- answer it.

