/** Meesho publishes no free-to-use mark: its wordmark in its own purple until the official SVG drops in here. */
const MEESHO_PURPLE = "#580A46";

export type PlatformMarkName = keyof typeof MARKS | "meesho";

const tileVariants = cva("inline-flex shrink-0 items-center justify-center overflow-hidden rounded-field border border-border bg-background", {
  variants: {
    size: { sm: "size-8 p-1.5", md: "size-10 p-2", lg: "size-12 p-2.5" },
  },
  defaultVariants: { size: "md" },
});

interface PlatformMarkProps extends VariantProps<typeof tileVariants> {
  name: PlatformMarkName;
  /** The platform's name, when the mark is the only label; without it the mark is decoration. */
  label?: string;
  className?: string;
}

/** A platform's mark on a quiet tile, so marks of different shapes sit in one row at one size. */
export function PlatformMark({ name, size, label, className }: PlatformMarkProps) {
  const a11y = label ? { role: "img" as const, "aria-label": label } : { "aria-hidden": true as const };
  if (name === "meesho") {
    return (
      <span className={cn(tileVariants({ size }), "px-0.5", className)} {...a11y}>
        <span className="text-2xs font-bold lowercase" style={{ color: MEESHO_PURPLE }}>
          {PLATFORM_MARKS_COPY.meesho}
        </span>
      </span>
    );
  }
  const mark: Mark = MARKS[name];
  return (
    <span className={cn(tileVariants({ size }), className)} {...a11y}>
      <svg viewBox={mark.viewBox} className="size-full" aria-hidden>
        {mark.paths.map((p) => (
          <path key={p.fill} d={p.d} fill={p.fill} />
        ))}
      </svg>
    </span>
  );
}
